using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Xml.Linq;

namespace Stellar.Tools.Modules;

/// <summary>
/// Turns the resolved modules into the MSBuild file the SDK imports.
/// </summary>
/// <remarks>
/// <para>
/// MSBuild cannot read JSON at evaluation time, and module references must exist at evaluation time for restore and
/// for the IDE to see them. So the modules are translated once, when they change, instead of being parsed by a task
/// on every build.
/// </para>
/// <para>
/// The file has two parts. <c>StellarModuleInfo</c> items are the catalog every project looks names up in. A
/// property group per module, active only in the project of that module, tells it who it is: its level, version
/// and dependencies. Each property only fills a value the project left empty, so a project overrides any of them.
/// </para>
/// </remarks>
public static class ModuleCatalogGenerator
{
    /// <summary>
    /// Renders the catalog.
    /// </summary>
    /// <param name="modules">The enabled modules.</param>
    /// <returns>The text of the MSBuild file.</returns>
    public static string Render(IEnumerable<ResolvedModule> modules)
    {
        var sorted = modules.OrderBy(module => module.Id, System.StringComparer.Ordinal).ToList();
        var project = new XElement("Project");
        var items = new XElement("ItemGroup");

        foreach (var module in sorted)
        {
            var item = new XElement("StellarModuleInfo",
                new XAttribute("Include", module.Id),
                new XAttribute("Version", $"[{module.Descriptor.Version}]"),
                new XAttribute("Level", module.Descriptor.Level.ToString()),
                new XAttribute("Link", module.Link.ToString()),
                new XAttribute("Source", module.Source.ToString()),
                new XAttribute("Dependencies", string.Join(";", module.Descriptor.Dependencies)));

            if (module.ProjectPath is { } path)
                item.Add(new XAttribute("ProjectPath", path));

            if (module.Directory is { } directory)
                item.Add(new XAttribute("ModuleDirectory", EnsureTrailingSeparator(directory)));

            items.Add(item);
        }

        project.Add(items);

        foreach (var module in sorted)
        {
            var group = new XElement("PropertyGroup",
                new XAttribute("Condition", $"'$(StellarModuleId)' == '{module.Id}'"),
                new XElement("StellarModuleKnown", "true"),
                Fill("StellarModuleLevel", module.Descriptor.Level.ToString()),
                Fill("StellarModuleVersion", module.Descriptor.Version ?? string.Empty),
                Fill("StellarModuleDependencies", string.Join(";", module.Descriptor.Dependencies)),
                Fill("StellarModuleNativeLibraries",
                    string.Join(";", module.NativeProjectPaths.Select(Path.GetFileNameWithoutExtension))));

            if (!string.IsNullOrEmpty(module.Descriptor.Description))
                group.Add(Fill("StellarModuleDescription", module.Descriptor.Description!));

            if (!string.IsNullOrEmpty(module.Descriptor.Repository))
                group.Add(Fill("StellarModuleRepository", module.Descriptor.Repository!));

            if (module.Directory is { } directory)
            {
                group.Add(Fill("StellarModuleDirectory", EnsureTrailingSeparator(directory)));
                group.Add(Fill("StellarModuleDescriptorFile", module.DescriptorFile!));
            }

            project.Add(group);
        }

        var document = new XDocument(
            new XComment(
                " Generated by 'stellar modules sync' from the module descriptors and manifests/engine.manifest.json. Do not edit. "),
            project);

        return document + "\n";
    }

    private static XElement Fill(string name, string value)
    {
        return new XElement(name, new XAttribute("Condition", $"'$({name})' == ''"), value);
    }

    private static string EnsureTrailingSeparator(string directory)
    {
        return directory.EndsWith(Path.DirectorySeparatorChar.ToString())
            ? directory
            : directory + Path.DirectorySeparatorChar;
    }
}
