using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Stellar.Tools.Build;

/// <summary>
/// What the executable of an application says about itself (the version information of Windows).
/// </summary>
public sealed class LauncherInfo
{
    /// <summary>Gets the simple name of the assembly of the application.</summary>
    public string Application { get; init; } = string.Empty;

    /// <summary>Gets the title of the application.</summary>
    public string Title { get; init; } = string.Empty;

    /// <summary>Gets the company.</summary>
    public string Company { get; init; } = string.Empty;

    /// <summary>Gets the product.</summary>
    public string Product { get; init; } = string.Empty;

    /// <summary>Gets the copyright.</summary>
    public string Copyright { get; init; } = string.Empty;

    /// <summary>Gets the version, as numbers (<c>1.2.3.4</c>).</summary>
    public string FileVersion { get; init; } = string.Empty;

    /// <summary>Gets the version, as people read it.</summary>
    public string InformationalVersion { get; init; } = string.Empty;
}

/// <summary>
/// Generates the launcher of an executable module.
/// </summary>
/// <remarks>
/// An application is a module like any other, a library: it has an entry point class, no <c>Main</c>. The launcher is
/// a separate small assembly next to it, behind the executable, and only hands the name of the application to the
/// runtime. The runtime loads the application like the modules, so the application can be unloaded like them.
/// </remarks>
public static class LauncherGenerator
{
    /// <summary>
    /// Generates the source of the launcher.
    /// </summary>
    /// <param name="info">The application.</param>
    /// <returns>The C# source code.</returns>
    public static string Generate(LauncherInfo info)
    {
        var attributes = new List<(string Name, string Value)>
        {
            ("AssemblyTitle", info.Title),
            ("AssemblyCompany", info.Company),
            ("AssemblyProduct", info.Product),
            ("AssemblyCopyright", info.Copyright),
            ("AssemblyFileVersion", info.FileVersion),
            ("AssemblyInformationalVersion", info.InformationalVersion)
        };

        var builder = new StringBuilder();
        builder.AppendLine("//------------------------------------------------------------------------------");
        builder.AppendLine("// This code is automatically generated by Stellar.Sdk build");
        builder.AppendLine("//------------------------------------------------------------------------------");
        builder.AppendLine();

        foreach (var (name, value) in attributes.Where(attribute => !string.IsNullOrEmpty(attribute.Value)))
            builder.AppendLine($"[assembly: global::System.Reflection.{name}(\"{Escape(value)}\")]");

        builder.AppendLine();
        builder.AppendLine("namespace Stellar.Generated;");
        builder.AppendLine();
        builder.AppendLine("internal static class StellarLauncher");
        builder.AppendLine("{");
        builder.AppendLine("    [global::System.STAThread]");
        builder.AppendLine("    private static int Main(string[] args) =>");
        builder.AppendLine(
            $"        global::Stellar.Runtime.Hosting.StellarRuntime.Run(\"{Escape(info.Application)}\", args);");
        builder.AppendLine("}");

        return builder.ToString();
    }

    private static string Escape(string value)
    {
        return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
    }
}
